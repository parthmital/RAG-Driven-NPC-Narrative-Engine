"""Embed the backend under test in the evaluation notebook, or check that it is in sync.

The Kaggle notebook must not depend on a network clone of this repository, so
the backend source it evaluates is stored inside the notebook as one
compressed, hashed bundle cell (tagged `backend-bundle`). The bundle holds:

- every non-test module of Backend/ and the W1 world seed, as the corrected
  system under test;
- Backend/game/validator.py and Backend/llm/prompt_builder.py at the commit
  evaluated before the Review-03 corrections, under legacy_v1/, as the
  "before" condition of the paired before-and-after comparison.

Usage (from the repository root, with the repo .venv):
    .venv/Scripts/python scripts/notebook_bundle.py           # rewrite the bundle cell
    .venv/Scripts/python scripts/notebook_bundle.py --check   # fail if it is stale
"""

from __future__ import annotations

import argparse
import base64
import gzip
import hashlib
import json
import subprocess
import sys
import textwrap
from pathlib import Path

import nbformat

ROOT = Path(__file__).resolve().parents[1]
NOTEBOOK = ROOT / "notebooks" / "npc-memory-state-benchmark.ipynb"
BACKEND = ROOT / "Backend"
TAG = "backend-bundle"
# The commit whose results the Review-02 manuscript reported (the "before" system)
LEGACY_COMMIT = "0ea345fe140b359d7e82e77ffb2fdfa74caf0e7c"
LEGACY_FILES = {
    "legacy_v1/validator.py": "Backend/game/validator.py",
    "legacy_v1/prompt_builder.py": "Backend/llm/prompt_builder.py",
}
EXCLUDED_DIRS = {"tests", "data", "__pycache__", ".venv"}


def _text(raw: bytes) -> str:
    # one byte form on every checkout, whatever core.autocrlf does
    return raw.decode("utf-8").replace("\r\n", "\n")


def collect() -> dict[str, str]:
    files = {}
    for path in sorted(BACKEND.rglob("*")):
        rel = path.relative_to(BACKEND)
        if not path.is_file() or EXCLUDED_DIRS.intersection(rel.parts):
            continue
        if path.suffix == ".py" or rel.as_posix() in (
            "game/world_seed.json",
            "requirements.txt",
        ):
            files[f"Backend/{rel.as_posix()}"] = _text(path.read_bytes())
    for name, source in LEGACY_FILES.items():
        raw = subprocess.run(
            ["git", "show", f"{LEGACY_COMMIT}:{source}"],
            cwd=ROOT,
            capture_output=True,
            check=True,
        ).stdout
        files[name] = _text(raw)
    return files


def digest(files: dict[str, str]) -> str:
    """Hash of the uncompressed contents, independent of gzip and base64 details."""
    h = hashlib.sha256()
    for name in sorted(files):
        h.update(name.encode() + b"\0" + files[name].encode("utf-8") + b"\0")
    return h.hexdigest()


def cell_source(files: dict[str, str]) -> str:
    payload = gzip.compress(
        json.dumps(files, sort_keys=True).encode("utf-8"), compresslevel=9, mtime=0
    )
    lines = textwrap.wrap(base64.b64encode(payload).decode("ascii"), 100)
    body = "\n".join(f'    "{line}"' for line in lines)
    return (
        "# Generated by scripts/notebook_bundle.py from Backend/ (do not edit by hand).\n"
        f'BACKEND_BUNDLE_SHA256 = "{digest(files)}"\n'
        f"BACKEND_BUNDLE_FILES = {len(files)}\n"
        f'BACKEND_LEGACY_COMMIT = "{LEGACY_COMMIT}"\n'
        f"BACKEND_BUNDLE = (\n{body}\n)"
    )


def bundle_cell(nb):
    cells = [c for c in nb.cells if TAG in c.get("metadata", {}).get("tags", [])]
    if len(cells) != 1:
        sys.exit(
            f"expected one cell tagged {TAG!r} in {NOTEBOOK.name}, found {len(cells)}"
        )
    return cells[0]


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check", action="store_true", help="fail if the bundle is stale"
    )
    args = parser.parse_args()

    nb = nbformat.read(NOTEBOOK, as_version=4)
    cell = bundle_cell(nb)
    files = collect()
    expected = cell_source(files)
    if args.check:
        if cell.source != expected:
            sys.exit(
                "The notebook's backend bundle is stale. Run "
                "`.venv/Scripts/python scripts/notebook_bundle.py` and commit the notebook."
            )
        print(
            f"Backend bundle in sync ({len(files)} files, sha256 {digest(files)[:12]})"
        )
        return
    cell.source = expected
    cell.outputs, cell.execution_count = [], None
    nbformat.validate(nb)
    nbformat.write(nb, NOTEBOOK)
    print(f"Wrote backend bundle: {len(files)} files, sha256 {digest(files)[:12]}")


if __name__ == "__main__":
    main()
